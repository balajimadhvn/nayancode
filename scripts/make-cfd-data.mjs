// Writes src/studios/genome/cfdData.ts: the Doench et al. 2016 CFD mismatch and PAM score tables for SpCas9.
// The numbers are the published tables (Doench et al. 2016, Nat Biotechnol 34:184, Supplementary Table 19). They are read from
// the MIT-licensed crisprScore package (Genentech, Inc.; https://github.com/crisprVerse/crisprScore, inst/cfd_cas9), which
// redistributes them; no GPL code is involved. Key = spacer base + protospacer (target-strand) base + position 1..20 (5' to 3').
//   node scripts/make-cfd-data.mjs
import { setDefaultResultOrder } from 'node:dns';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
setDefaultResultOrder('ipv4first');
const base = 'https://raw.githubusercontent.com/crisprVerse/crisprScore/devel/inst/cfd_cas9/';
const read = async (f) => Object.fromEntries((await (await fetch(base + f)).text()).trim().split('\n').map((l) => { const [k, v] = l.trim().split(/\s+/); return [k, Number(v)]; }));
const mm = await read('cfd.mm.scores.cas9.txt'), pam = await read('cfd.pam.scores.cas9.txt');
if (Object.keys(mm).length !== 240 || Object.keys(pam).length !== 16) throw new Error('unexpected table size');
const out = `// Generated by scripts/make-cfd-data.mjs. Do not edit.
// CFD (cutting frequency determination) tables, Doench JG, et al. (2016) Nat Biotechnol 34:184-191, Supplementary Table 19,
// as redistributed under the MIT licence by crisprScore (Copyright (c) 2022 Genentech, Inc.).
/** Mismatch weights: key = spacer base + protospacer base (target-strand letters) + position 1..20 (5' to 3', PAM-proximal = 20). */
export const CFD_MM: Record<string, number> = ${JSON.stringify(mm)};
/** PAM weights keyed by the last two bases of the NGG PAM (N is ignored). */
export const CFD_PAM: Record<string, number> = ${JSON.stringify(pam)};
`;
writeFileSync(fileURLToPath(new URL('../src/studios/genome/cfdData.ts', import.meta.url)), out);
console.log('wrote cfdData.ts');
